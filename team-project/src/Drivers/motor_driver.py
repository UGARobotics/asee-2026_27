from machine import Pin, PWM

class MotorDriver:
    def __init__(self, pwm_pin, in1_pin, in2_pin, enc_a_pin, enc_b_pin):
        # Motor PWM & Direction setup
        self.pwm = PWM(Pin(pwm_pin))
        self.in1 = Pin(in1_pin, Pin.OUT)
        self.in2 = Pin(in2_pin, Pin.OUT)
        self.pwm.freq(1000)

        self.enc_b_pin = Pin(enc_b_pin, Pin.IN, Pin.PULL_UP)
        self.encoder_count = 0

        self.enc_a = Pin(enc_a_pin, Pin.IN, Pin.PULL_UP)
        self.enc_a.irq(trigger=Pin.IRQ_RISING, handler=self.encoder_callback)

    def encoder_callback(self, pin):
        # Evaluate phase B to determine direction
        if self.enc_b_pin.value() == 1:
            self.encoder_count += 1
        else:
            self.encoder_count -= 1

    def set_speed(self, speed):
        pass

    def drive(self, speed):
        """
        Speed: -65535 to 65534
        (positive = forward, negative = backward)
        """
        # check this because it was generated by AI and might be wrong
        if speed > 0:
            self.in1.value(1)
            self.in2.value(0)
            self.pwm.duty_u16(speed)
        elif speed < 0:
            self.in1.value(0)
            self.in2.value(1)
            self.pwm.duty_u16(-speed)
        else:
            self.in1.value(0)
            self.in2.value(0)
            self.pwm.duty_u16(0)


    def get_encoder_count(self):
        return self.encoder_count

    def reset_encoder_count(self):
        self.encoder_count = 0